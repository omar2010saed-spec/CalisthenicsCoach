    CHEST("الصدر"),
    BACK("الظهر"),
    SHOULDERS("الأكتاف"),
    BICEPS("البايسبس"),
    TRICEPS("الترايسبس"),
    FOREARMS("الساعد"),
    ABS("عضلات البطن"),
    CORE("ثبات الجذع"),
    LOWER_BACK("أسفل الظهر"),
    QUADS("الفخذ الأمامي"),
    HAMSTRINGS("الفخذ الخلفي"),
