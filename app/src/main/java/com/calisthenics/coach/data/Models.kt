enum class Kind { WARMUP, STRENGTH, COOLDOWN }

enum class Equip(val ar: String) {
    BODY("وزن الجسم"),
    BAND("حلقة مقاومة قصيرة")
}

/**
 * Side-view body pose (figure faces right): 13 joints as x,y pairs in body-height units with the hip at the origin:
 * 0 head, 1 shoulder, 2 elbow, 3 hand, 4 hip, 5 knee, 6 ankle, 7 toe, then the far limbs 8 elbow, 9 hand,
 * 10 knee, 11 ankle, 12 toe. [lift] raises the whole body off the floor (jumps). Generated by tools/gen_poses.py.
 */
class Pose(val p: FloatArray, val lift: Float = 0f) {
    companion object {
        const val HEAD = 0
        const val SHOULDER = 1
        const val ELBOW = 2
        const val HAND = 3
        const val PELVIS = 4
        const val KNEE = 5
        const val FOOT = 6
    }
}

/** Two keyframes that the illustration animates between. bandAt = joint index that gets a band ring. */
class Anim(val a: Pose, val b: Pose, val bandAt: Int? = null)

data class Exercise(
    val id: String,
    val en: String,
    val ar: String,
    val muscle: Muscle,
    val also: String,
    val kind: Kind,
    val minStage: Int,
    val equip: Equip,
    val timed: Boolean,
    val perSide: Boolean,
    val sets: Int,
    val amount: Int,
    val rest: Int,
    val difficulty: Int,
    val anim: Anim,
    val start: String,
    val steps: List<String>,
    val breathing: String,
    val mistakes: List<String>,
    val safety: String,
    val easier: String?,
    val harder: String?
) {
    val amountLabel: String
        get() = if (timed) "$amount ثانية" else "$amount تكرار"
}

enum class Slot(val ar: String) {
    PUSH("دفع (صدر)"),
    SHOULDER("أكتاف"),
    TRICEPS("ترايسبس"),
    BACK("ظهر"),
    BICEPS("بايسبس"),
    FOREARM("ساعد"),
    QUAD("فخذ أمامي"),
    HAM("فخذ خلفي"),
    GLUTE("أرداف"),
    CALF("سمانة"),
    HIP("ورك"),
    ABS("بطن"),
    CORE("ثبات الجذع"),
    LOWBACK("أسفل الظهر")
}

/** A kind of workout session. The stage's rotation decides which one comes next. */
enum class SessionType(val ar: String, val desc: String, val slots: List<Slot>) {
    FULL_A("تمرين كامل (أ)", "صدر وأكتاف وترايسبس وفخذ وبطن", listOf(Slot.PUSH, Slot.QUAD, Slot.SHOULDER, Slot.ABS, Slot.TRICEPS, Slot.CALF)),
    FULL_B("تمرين كامل (ب)", "أرداف وظهر وجذع وفخذ خلفي", listOf(Slot.GLUTE, Slot.BACK, Slot.CORE, Slot.HAM, Slot.BICEPS, Slot.LOWBACK)),
    FULL_C("تمرين كامل (ج)", "دفع وسحب وساقان وورك", listOf(Slot.PUSH, Slot.QUAD, Slot.CORE, Slot.BACK, Slot.HIP, Slot.ABS, Slot.FOREARM)),
    PUSH("دفع", "صدر وأكتاف وترايسبس وجذع", listOf(Slot.PUSH, Slot.SHOULDER, Slot.TRICEPS, Slot.CORE, Slot.ABS)),
    LEGS("ساقان وأرداف", "فخذ أمامي وخلفي وأرداف وسمانة وورك", listOf(Slot.QUAD, Slot.HAM, Slot.GLUTE, Slot.CALF, Slot.HIP)),
    PULL("ظهر وجذع", "ظهر وبايسبس وأسفل الظهر وبطن وساعد", listOf(Slot.BACK, Slot.BICEPS, Slot.LOWBACK, Slot.CORE, Slot.ABS, Slot.FOREARM)),
    MIX("تمرين شامل", "دفع وساقان وظهر وجذع معًا", listOf(Slot.PUSH, Slot.QUAD, Slot.BACK, Slot.CORE, Slot.GLUTE, Slot.SHOULDER))
}

data class Stage(
    val number: Int,
    val name: String,
    val summary: String,
    val rotation: List<SessionType>,  // session types in the order they are trained
    val trainingDays: Int,
    val setsRange: String,
    val rest: String,
    val progression: List<String>,    // criteria to move on
    val safety: List<String>,
    val minWorkoutsLast28: Int,
    val pushTarget: Int,              // reps of the stage's main push exercise to show readiness
    val plankTarget: Int              // seconds
)

